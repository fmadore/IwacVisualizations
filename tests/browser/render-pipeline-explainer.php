/** msgid => msgstr from a .po file: enough of the format for fr.po. */
function poCatalogue(string $path): array
{
    $out = [];
    $id = $str = null;
    $target = null;
    $unquote = static fn (string $q): string => stripcslashes(substr($q, 1, -1));
    foreach (preg_split('/\R/', (string) file_get_contents($path)) as $line) {
        if (str_starts_with($line, 'msgid ')) {
            if ($id !== null && $str !== null && $id !== '') $out[$id] = $str;
            $id = $unquote(substr($line, 6));
            $str = null;
            $target = 'id';
        } elseif (str_starts_with($line, 'msgstr ')) {
            $str = $unquote(substr($line, 7));
            $target = 'str';
        } elseif (str_starts_with($line, '"') && $target !== null) {
            if ($target === 'id') $id .= $unquote($line); else $str .= $unquote($line);
        }
    }
    if ($id !== null && $str !== null && $id !== '') $out[$id] = $str;
    return $out;
}

final class PipelineFixtureView
{
    public function __construct(private array $catalogue) {}

    public function plugin(string $name): callable
    {
        return static fn ($value) => htmlspecialchars((string) $value, ENT_QUOTES, 'UTF-8');
    }

    public function translate(string $text): string
    {
        return ($this->catalogue[$text] ?? '') !== '' ? $this->catalogue[$text] : $text;
    }

    /** The slice of `common/iwac-block-shell` this block relies on. */
    public function partial(string $name, array $args): string
    {
        if ($name !== 'common/iwac-block-shell') {
            throw new RuntimeException("The fixture renders no partial '$name'.");
        }
        $data = '';
        foreach (['base-path' => ''] + $args['data'] as $key => $value) {
            $data .= ' data-' . $key . '="' . htmlspecialchars((string) $value, ENT_QUOTES, 'UTF-8') . '"';
        }
        return '<div class="iwac-vis-block ' . $args['blockClass'] . '"' . $data . ">\n"
            . $args['prerendered'] . "\n</div>\n";
    }

    public function render(string $preset, string $level, string $instance): string
    {
        $content = PipelinePresets::content($preset, $level, fn (string $t): string => $this->translate($t));
        ob_start();
        include __DIR__ . '/../../view/common/block-layout/pipeline-explainer.phtml';
        return ob_get_clean();
    }
}


#!/usr/bin/env node
/**
 * Generate asset/css/iwac-embed-tokens.css — the theme's tokens as a flat
 * stylesheet, for the one place this module renders WITHOUT the theme's CSS.
 *
 *   npm run build:embed-tokens   write it from tokens.json
 *   npm run lint:embed-tokens    fail if it no longer matches tokens.json
 *
 * WHY. The embed routes (`layout/embed.phtml`) ship a block into a foreign
 * page's iframe with no theme stylesheet, so every `var(--token, fallback)` in
 * iwac-core.css renders its fallback — and fallbacks are the LIGHT values by
 * contract. `?theme=dark` stamps `data-theme="dark"`, but nothing declared a
 * dark palette: only the brand accent was lightened (iwac-embed.css). The
 * panels painted light surfaces while `iwac-theme.js`, seeing `data-theme`,
 * handed ECharts its FALLBACK_DARK ink (#e7e4df) — light text on a light panel.
 *
 * The fix is not a hand-written dark block (that would be a second copy of the
 * palette, which is exactly what the token contract forbids) but a generated
 * one: `tokens.json` already publishes every token resolved to a literal for
 * both themes (`light`/`dark` for colours, `values.light`/`values.dark` for
 * everything else), so this sheet is those maps, printed. Literals, not
 * compositions, so the substitution-scope trap (a composed token frozen at the
 * light value on <body>) cannot occur here.
 *
 *   :root                 light colours + light values
 *   [data-theme="dark"]   dark colours + dark values (the embed stamps both
 *                         <html> and <body>; a token dark does not redeclare —
 *                         --white, --black — inherits the light constant)
 *
 * The brand-accent override in iwac-embed.css outranks both blocks on
 * specificity, so `?primary=` and the theme's admin-set colour still win.
 *
 * The theme-token guard skips this file (it is all literals by construction);
 * the --check mode here is what asserts it instead.
 *
 * It also writes config/theme-seeds.php: the theme's two brand seeds, which
 * the embed layout compares the theme's `primary_color` / `secondary_color`
 * settings against. A setting EQUAL to its seed needs no override (the sheet
 * above already carries the theme's own derivation of it), and overriding
 * with the raw seed is what painted every live embed in #e64a19 (3.82:1 on
 * the surface) beside a canonical #ce4115. tokens.json does not ship in the
 * release archive, so PHP reads this generated copy instead.
 */
'use strict';

const { readFileSync, writeFileSync, existsSync } = require('fs');
const { join } = require('path');

const ROOT = join(__dirname, '..');
const TOKENS = join(ROOT, 'tokens.json');
const OUT = join(ROOT, 'asset', 'css', 'iwac-embed-tokens.css');
const SEEDS_OUT = join(ROOT, 'config', 'theme-seeds.php');
const CHECK = process.argv.includes('--check');

function render(tokens) {
    const block = (selector, colours, values) => {
        const merged = Object.assign({}, values || {}, colours || {});
        const lines = Object.keys(merged).sort().map((name) => `    ${name}: ${merged[name]};`);
        return `${selector} {\n${lines.join('\n')}\n}\n`;
    };
    const values = tokens.values || {};
    return [
        '/*',
        ` * GENERATED by scripts/build-embed-tokens.js from tokens.json (IWAC-theme ${tokens.themeVersion || 'unknown'}).`,
        ' * Do not edit: run `npm run build:embed-tokens` after `npm run sync:tokens` in IWAC-theme.',
        ' * Loaded only by the embed layout, which renders without the theme stylesheet.',
        ' */',
        block(':root', tokens.light, values.light),
        block('[data-theme="dark"]', tokens.dark, values.dark),
    ].join('\n');
}

function renderSeeds(tokens) {
    const seeds = tokens.seeds || {};
    const hex = (name) => {
        const value = String(seeds[name] || '').toLowerCase();
        if (!/^#[0-9a-f]{6}$/.test(value)) {
            console.error(`✗ tokens.json seeds.${name} is not a #rrggbb hex: ${JSON.stringify(seeds[name])}`);
            process.exit(1);
        }
        return value;
    };
    return [
        '<?php',
        `// GENERATED by scripts/build-embed-tokens.js from tokens.json (IWAC-theme ${tokens.themeVersion || 'unknown'}).`,
        '// Do not edit: run `npm run build:embed-tokens` after `npm run sync:tokens` in IWAC-theme.',
        '//',
        "// The theme's brand seeds. layout/embed.phtml skips its brand-accent",
        '// override when a setting equals its seed: the embed token sheet already',
        "// carries the theme's derivation of that seed.",
        'return [',
        `    'primary'   => '${hex('--primary-base')}',`,
        `    'secondary' => '${hex('--secondary-base')}',`,
        // The theme's webfont request, once tokens.json publishes it (theme
        // 2.24); until then EmbedBrand::WEBFONT_URL is the copy.
        ...(typeof tokens.fontsUrl === 'string' && /^https:\/\/[^'\\]+$/.test(tokens.fontsUrl)
            ? [`    'fontsUrl'  => '${tokens.fontsUrl}',`]
            : []),
        '];',
        '',
    ].join('\n');
}

if (!existsSync(TOKENS)) {
    console.error('✗ tokens.json not found — run `npm run sync:tokens` in IWAC-theme');
    process.exit(1);
}
const tokens = JSON.parse(readFileSync(TOKENS, 'utf8'));
const css = render(tokens);
const seeds = renderSeeds(tokens);

if (CHECK) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== css) {
        console.error('✗ asset/css/iwac-embed-tokens.css does not match tokens.json — run `npm run build:embed-tokens` (then `npm run build:css`)');
        process.exit(1);
    }
    const currentSeeds = existsSync(SEEDS_OUT) ? readFileSync(SEEDS_OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (currentSeeds !== seeds) {
        console.error('✗ config/theme-seeds.php does not match tokens.json — run `npm run build:embed-tokens`');
        process.exit(1);
    }
    console.log('✓ embed token sheet and theme seeds match tokens.json');
} else {
    writeFileSync(OUT, css);
    writeFileSync(SEEDS_OUT, seeds);
    console.log(`  wrote asset/css/iwac-embed-tokens.css (${css.split('\n').length} lines) and config/theme-seeds.php`);
}

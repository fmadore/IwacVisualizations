'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const registry = JSON.parse(fs.readFileSync(path.join(root, 'config/sentiment-models.json'), 'utf8'));
const ids = registry.active.map(m => m.id);
if (new Set(ids).size !== ids.length || registry.active.some(m => !registry.hiddenStems.includes(m.stem))) {
    throw new Error('Model IDs must be unique and active stems must be hidden.');
}
if (ids.some(id => Object.hasOwn(registry.labels, id))) throw new Error('Active labels must come from active model names.');
const labels = { ...Object.fromEntries(registry.active.map(m => [m.id, m.name])), ...registry.labels };
function php(value) {
    if (typeof value === 'string') return "'" + value.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
    if (Array.isArray(value)) return '[' + value.map(php).join(', ') + ']';
    return '[' + Object.entries(value).map(([k, v]) => php(k) + ' => ' + php(v)).join(', ') + ']';
}
function write(file, content) {
    const target = path.join(root, file);
    if (process.argv.includes('--check')) {
        if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
            throw new Error('Stale model registry: ' + file);
        }
    } else fs.writeFileSync(target, content);
}
const info = Object.fromEntries(registry.active.map(({ id, stem, ...display }) => [stem, display]));
write('src/Sentiment/ModelRegistry.php', '<?php\ndeclare(strict_types=1);\nnamespace IwacVisualizations\\Sentiment;\n\n'
    + '// Generated by scripts/build-model-registry.js from config/sentiment-models.json.\n'
    + 'final class ModelRegistry\n{\n'
    + '    public const STEMS = ' + php(registry.hiddenStems) + ';\n'
    + '    public const MODELS = ' + php(registry.active.map(m => m.stem)) + ';\n'
    + '    public const INFO = ' + php(info) + ';\n}\n');
const controls = 'asset/js/charts/shared/panels-controls.js';
const original = fs.readFileSync(path.join(root, controls), 'utf8');
write(controls, original.replace(/var SENTIMENT_MODEL_LABELS = \{[\s\S]*?\n {4}\};/,
    'var SENTIMENT_MODEL_LABELS = ' + JSON.stringify(labels, null, 4).replace(/\n/g, '\n    ') + ';'));
